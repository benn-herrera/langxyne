"""CLI: validate an .adef.toml definition and write the selected outputs (see `EMITTERS`)
into the generated directory, or (`--check`) compare them with the files there, or (gendeps
mode) print a Makefile fragment naming those outputs for one definition. The definition's
`_general._name` names every output.
"""

import argparse
import dataclasses
import sys
from collections.abc import Callable, Iterable
from pathlib import Path

from langxyne import model, naming
from langxyne.emitters import EMITTERS
from langxyne.emitters.emitter import ToolError

SUFFIX = ".adef.toml"
GENDEPS_BANNER = "# GENERATED by langxyne gendeps; do not edit."
TOKENS = tuple(EMITTERS)
# A WASI build of the library selects the shim and the Node binding by name, together.
DEFAULT_TOKENS = tuple(t for t in TOKENS if t not in ("wasm_rs", "node"))


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["gendeps"]:
        return _gendeps_main(argv[1:])
    return _generate_main(argv)


def _outputs(text: str) -> tuple[str, ...]:
    """`--outputs`: comma-separated tokens, each known and none repeated, returned in
    `TOKENS` order."""
    tokens = text.split(",")
    valid = ", ".join(TOKENS)
    for i, token in enumerate(tokens):
        if token not in TOKENS:
            raise argparse.ArgumentTypeError(f"unknown output '{token}' (valid: {valid})")
        if token in tokens[:i]:
            raise argparse.ArgumentTypeError(f"output '{token}' repeated (valid: {valid})")
    return tuple(t for t in TOKENS if t in tokens)


def _add_outputs_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--outputs",
        type=_outputs,
        default=DEFAULT_TOKENS,
        help=f"comma-separated outputs to produce, from {','.join(TOKENS)} (default: {','.join(DEFAULT_TOKENS)})",
    )


def _add_link_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--link",
        choices=naming.LINK_MODES,
        default=naming.DEFAULT_LINK,
        help=f"how a consumer's build links the library (default: {naming.DEFAULT_LINK})",
    )


def _add_schema_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--no-schema",
        dest="schema",
        action="store_false",
        help="skip the api_def.schema.json pass the loader otherwise runs first where jsonschema is installed",
    )


def _flag_objections(flag: str, value: str | None, *, names: str, check: Callable[[str, str], None]) -> list[str]:
    """The objections to a flag the outputs spell: not empty, since an empty one names no
    `names`, and held to `check`, the rule of what it names."""
    if value is None:
        return []
    if not value:
        return [f"{flag} must name a {names}"]
    try:
        check(value, flag)
    except model.DefinitionError as e:
        return [str(e)]
    return []


def _objections(api: model.Api, outputs: tuple[str, ...]) -> list[str]:
    """Every selected emitter's objection to `api`, one line per distinct message:
    objections from different emitters that share the same text after their own
    `<emitter>: ` prefix are reported once, under every emitter that raised it,
    comma-joined in `EMITTERS` order."""
    labels_by_message: dict[str, list[str]] = {}
    for token in outputs:
        emitter = EMITTERS[token]
        for objection in emitter.validate(api):
            message = objection.removeprefix(f"{emitter.LABEL}: ")
            labels_by_message.setdefault(message, []).append(emitter.LABEL)
    return [f"{', '.join(labels)}: {message}" for message, labels in labels_by_message.items()]


def _report(definition: Path | str, objections: Iterable[object]) -> int:
    """Print each objection to `definition` on stderr; the exit code for them, 2."""
    for objection in objections:
        print(f"langxyne: {definition}: {objection}", file=sys.stderr)
    return 2


def _generate_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="generate userspace API artifacts from an API definition")
    parser.add_argument("definition", type=Path, help="path to a *.adef.toml file")
    parser.add_argument("--generated", type=Path, required=True, help="output directory")
    parser.add_argument(
        "--project",
        required=True,
        help="project name, its directory's: the include subdirectory and the base of each _wrapped_api._headers path",
    )
    parser.add_argument(
        "--library",
        help="the library's name, which the Lua module loads and the Rust binding links (default: _general._bound_library)",
    )
    _add_link_argument(parser)
    _add_outputs_argument(parser)
    _add_schema_argument(parser)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when a selected output differs from its file under --generated or is missing",
    )
    args = parser.parse_args(argv)
    outputs: tuple[str, ...] = args.outputs

    definition: Path = args.definition
    if not definition.name.endswith(SUFFIX):
        print(f"langxyne: {definition}: file name must end in {SUFFIX}", file=sys.stderr)
        return 2

    source = definition.name
    project: str = args.project
    flag = _flag_objections("--project", project, names="directory", check=model.check_literal_text)
    # every banner carries it; a path separator, and so `*/`, cannot be in a file's name
    flag += _flag_objections("the definition's file name", source, names="file", check=model.check_literal_text)
    flag += _flag_objections("--library", args.library, names="library", check=model.check_library_name)
    try:
        api = model.load(definition, schema=args.schema)
    except model.DefinitionError as e:
        objections = [str(o) for o in e.objections()]
    else:
        # a refused --library still stands in for the definition's, so it draws no objection of its absence
        name = args.library if args.library is not None else api.library.name
        api = dataclasses.replace(api, library=model.Library(name=name, link=args.link))
        objections = _objections(api, outputs)
    objections += flag
    if objections:
        return _report(definition, objections)

    texts: dict[Path, str] = {}
    try:
        for token in outputs:
            emitter = EMITTERS[token]
            texts[emitter.output_path(name=api.name, project=project)] = emitter.emit(
                api, source_name=source, name=api.name, project=project
            )
            texts.update(emitter.companions(api, name=api.name))
    except ToolError as e:
        print(f"langxyne: {e}", file=sys.stderr)
        return 2

    generated: Path = args.generated
    if args.check:
        return _check(name=api.name, generated=generated, texts=texts)
    for relpath, text in texts.items():
        out_path = generated / relpath
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(text, encoding="utf-8")

    written = " ".join(str(relpath) for relpath in texts)
    print(f"langxyne: {api.name}: wrote {written} under {generated}", file=sys.stderr)
    return 0


def _check(*, name: str, generated: Path, texts: dict[Path, str]) -> int:
    """`--check`: each output's text against its file under `generated`, read back as text
    with the newline translation generation writes it through, opening nothing for writing.
    One line on stderr per output that differs or is missing and exit 1, else one line and
    exit 0; a file that cannot be read exits 2."""
    stale: list[str] = []
    for relpath, text in texts.items():
        try:
            same = (generated / relpath).read_text(encoding="utf-8") == text
        except FileNotFoundError:
            stale.append(f"{relpath} is missing")
            continue
        except UnicodeDecodeError:
            same = False
        except OSError as e:
            print(f"langxyne: {e}", file=sys.stderr)
            return 2
        if not same:
            stale.append(f"{relpath} differs")
    for line in stale:
        print(f"langxyne: {name}: {line}", file=sys.stderr)
    if stale:
        return 1
    checked = " ".join(str(relpath) for relpath in texts)
    print(f"langxyne: {name}: {checked} under {generated} match", file=sys.stderr)
    return 0


def _gendeps_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="langxyne gendeps",
        description="print a Makefile fragment naming the outputs for a definition",
    )
    parser.add_argument("definitions", nargs="*", help="path to a *.adef.toml file")
    _add_link_argument(parser)
    _add_outputs_argument(parser)
    _add_schema_argument(parser)
    args = parser.parse_args(argv)

    if len(args.definitions) != 1:
        print("langxyne: gendeps takes exactly one definition", file=sys.stderr)
        return 2

    definition = args.definitions[0]
    if not definition.endswith(SUFFIX):
        print(f"langxyne: {definition}: file name must end in {SUFFIX}", file=sys.stderr)
        return 2
    try:
        api = model.load(Path(definition), schema=args.schema)
    except model.DefinitionError as e:
        return _report(definition, e.objections())

    paths: list[Path] = []
    for token in args.outputs:
        emitter = EMITTERS[token]
        paths.append(emitter.output_path(name=api.name, project="$(BASE)"))
        paths += [relpath for relpath, _ in emitter.companions(api, name=api.name)]
    block = _gendeps_block(definition=definition, paths=paths, outputs=args.outputs, link=args.link)
    sys.stdout.write(GENDEPS_BANNER + "\n" + block)
    return 0


def _gendeps_block(*, definition: str, paths: list[Path], outputs: tuple[str, ...], link: str) -> str:
    """The make fragment for `definition`'s selected outputs, whose files, each output's
    companions beside it, are `paths`: the generator's only make-specific text. Another build
    system (ninja, gradle, ...) is another renderer of the same inputs, chosen by a `gendeps`
    flag, and nothing above this function changes. The recipe passes `link` on only where it
    is not the default."""
    targets = " \\\n".join(f"  $(GEN)/{path}" for path in paths)
    link_flag = "" if link == naming.DEFAULT_LINK else f" --link={link}"
    recipe = (
        "PYTHONPATH=$(LANGXYNE) PYTHONDONTWRITEBYTECODE=1 "
        f"python3 -m langxyne $< --generated $(GEN) --project $(BASE) --outputs={','.join(outputs)}{link_flag}"
    )
    return f"GENERATED := \\\n{targets}\n\n$(GENERATED) &: {definition}\n\t{recipe}\n"


if __name__ == "__main__":
    sys.exit(main())
