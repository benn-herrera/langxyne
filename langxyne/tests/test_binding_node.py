import dataclasses
import unittest
from pathlib import Path

from langxyne import model, naming
from langxyne.emitters import emit_binding_node
from langxyne.tests.support import KITCHEN_SINK, load, mutate
from langxyne.tests.support_xy32 import XY32


def validate(text: str, *, link: str = naming.SHARED, library: str | None = "xy") -> list[str]:
    api = dataclasses.replace(load(text), library=model.Library(name=library, link=link))
    return emit_binding_node.validate(api)


class Outputs(unittest.TestCase):
    """SPEC "Outputs": the module and its declarations beside it, each under its banner."""

    def test_the_module_and_its_declarations_beside_it(self) -> None:
        self.assertEqual(emit_binding_node.output_path(name="xy_api", project="xy"), Path("node/xy_api.mjs"))
        [(path, _)] = emit_binding_node.companions(load(XY32), name="xy_api")
        self.assertEqual(path, Path("node/xy_api.d.mts"))

    def test_each_starts_with_its_banner(self) -> None:
        api = load(XY32)
        module = emit_binding_node.emit(api, source_name="xy_api.adef.toml", name="xy_api", project="xy")
        self.assertEqual(module.splitlines()[0], "// GENERATED by langxyne from xy_api.adef.toml; do not edit.")
        [(_, declarations)] = emit_binding_node.companions(api, name="xy_api")
        self.assertEqual(declarations.splitlines()[0], "// GENERATED by langxyne beside xy_api.mjs; do not edit.")


class OutExtent(unittest.TestCase):
    """SPEC Node, each call: an `out` buffer whose bytes would pass 2**31 - 1 is refused naming it."""

    def test_the_largest_count_is_whole_elements_within_the_extent(self) -> None:
        module = emit_binding_node.emit(load(XY32), source_name="xy_api.adef.toml", name="xy_api", project="xy")
        for count, bound, message in (
            ("_c_items", 178956970, "Port.list: items"),  # 12-byte entries
            ("_c_pdst", 2147483647, "Port.recv: pdst"),  # bytes
        ):
            with self.subTest(buffer=message):
                self.assertIn(f"if ({count} > {bound}) {{", module)
                self.assertIn(f'throw new RangeError("{message} would pass 2147483647 bytes");', module)


class Validate(unittest.TestCase):
    def test_xy32_draws_no_objection(self) -> None:
        self.assertEqual(validate(XY32), [])

    def test_every_64_bit_position_of_kitchen_sink(self) -> None:
        refused = "a 64-bit type, {}, is not implemented"
        self.assertEqual(
            validate(KITCHEN_SINK),
            [
                f"node: {where}: {refused.format(t)}"
                for where, t in (
                    ("struct.stats.bytes", "u64"),
                    ("boxed_scalar.offset._base_type", "u64"),
                    ("function.send.buf._count", "u64"),
                    ("function.seek.offset", "u64"),
                    ("function.tune.big", "i64"),
                    ("function.tune.pnext", "i64"),
                    ("function.list.items._count", "u64"),
                    ("callback.on_batch.seen._count", "u64"),
                    ("callback.on_batch.fresh._count", "u64"),
                )
            ],
        )

    def test_a_64_bit_array_element_and_callback_value(self) -> None:
        text = mutate(XY32, 'cuts = { _type = "cut"', 'cuts = { _type = "i64"')
        text = mutate(text, '_return = "flow"\nmode = "mode"', '_return = "flow"\nmode = "u64"')
        self.assertEqual(
            validate(text),
            [
                "node: function.stream.cuts: a 64-bit type, i64, is not implemented",
                "node: callback.on_mode.mode: a 64-bit type, u64, is not implemented",
            ],
        )

    def test_a_struct_field_of_opaque_type(self) -> None:
        text = mutate(XY32, "[struct.entry]", '[struct.held]\nh = "token"\n\n[struct.entry]')
        self.assertEqual(validate(text), ["node: struct.held.h: a field of opaque_ref type is not implemented"])

    def test_a_static_link(self) -> None:
        self.assertEqual(
            validate(XY32, link=naming.STATIC),
            ["node: --link=static: the Node binding loads its module at run time and cannot link it statically"],
        )

    def test_no_library(self) -> None:
        self.assertEqual(
            validate(XY32, library=None), ["node: no library named; set _general._bound_library or --library"]
        )

    def test_a_reserved_word_the_module_binds(self) -> None:
        self.assertEqual(
            validate(mutate(XY32, 'unit = "u32"', 'var = "u32"')),
            ["node: function.open_port.var: 'var' is a JavaScript reserved word"],
        )

    def test_a_parameter_named_like_a_global_or_a_module_name(self) -> None:
        for name in ("Object", "load", "Stats"):
            with self.subTest(name=name):
                self.assertEqual(
                    validate(mutate(XY32, 'unit = "u32"', f'{name} = "u32"')),
                    [f"node: function.open_port.{name}: '{name}' is a name the generated code uses"],
                )

    def test_a_free_function_named_like_a_parameter_of_load(self) -> None:
        for name in ("wasi", "path"):
            with self.subTest(name=name):
                self.assertEqual(
                    validate(mutate(XY32, "[function.reset]", f"[function.{name}]")),
                    [f"node: function.{name}: '{name}' is a name the generated code uses"],
                )

    def test_a_struct_field_named_constructor(self) -> None:
        text = mutate(XY32, 'count = { _type = "u32", _docstring = "items seen" }', 'constructor = "u32"')
        self.assertEqual(
            validate(text), ["node: struct.stats.constructor: 'constructor' is a name the generated code uses"]
        )

    def test_a_name_defined_twice_at_module_scope(self) -> None:
        self.assertEqual(
            validate(mutate(XY32, "[struct.entry]", '[struct.view]\nh = "u32"\n\n[struct.entry]')),
            ["node: module scope: View would be defined more than once, by struct.view and the module's own names"],
        )

    def test_a_name_a_union_defines(self) -> None:
        self.assertEqual(
            validate(mutate(XY32, "[struct.entry]", '[struct.note_sequence]\nh = "u32"\n\n[struct.entry]')),
            ["node: struct.note_sequence: module scope name NoteSequence already defined by union 'note'"],
        )

    def test_a_name_defined_twice_in_a_class(self) -> None:
        self.assertEqual(
            validate(mutate(XY32, "[function.send]", "[function.handle]")),
            ["node: class Port: handle would be defined more than once, by the class's own member and function.handle"],
        )
