import contextlib
import re
import tempfile
import unittest
from pathlib import Path

from langxyne import __main__ as langxyne_main
from langxyne.tests.support import FIXTURE, FIXTURES, KITCHEN_SINK, TWO_BAD_RETURNS, run_main
from langxyne.tests.support_cli import output_paths, run, write


class Gendeps(unittest.TestCase):
    def definition(self, text: str = FIXTURE) -> str:
        """`text` written as `a.adef.toml`, a file name unlike its `_name`, under a fresh
        directory removed at the end of the test; its path."""
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        path = Path(tmp.name) / "a.adef.toml"
        path.write_text(text, encoding="utf-8")
        return str(path)

    def run_gendeps(self, args: list[str]) -> tuple[int, str]:
        code, stdout, _ = run_main(["gendeps", *args])
        return code, stdout

    def test_fragment_lists_the_output_paths_named_by_the_definition_in_one_grouped_rule(self) -> None:
        definition = self.definition()
        code, out = self.run_gendeps([definition])
        self.assertEqual(code, 0)
        self.assertEqual(out.splitlines()[0], "# GENERATED by langxyne gendeps; do not edit.")
        targets = re.search(r"GENERATED := \\\n((?:  .*\\\n)*  .*)\n", out).group(1)
        paths = output_paths(name="xy_api", project="$(BASE)")
        expected = []
        for token in langxyne_main.DEFAULT_TOKENS:
            expected.append(f"$(GEN)/{paths[token]}")
            if token == "lua":
                # FIXTURE's u64 field brings the Lua module's companion, listed beside it
                expected.append("$(GEN)/lua/i64.lua")
        self.assertEqual([t.strip().rstrip(" \\") for t in targets.splitlines()], expected)
        self.assertIn(f"$(GENERATED) &: {definition}\n\t", out)
        self.assertIn("--outputs=h,hpp,lua,stub_cpp,rs,abi_rs,stub_rs,go,py\n", out)

    def test_outputs_selects_the_targets_and_the_recipe_passes_it_on(self) -> None:
        code, out = self.run_gendeps(["--outputs=lua,h", self.definition()])
        self.assertEqual(code, 0)
        paths = output_paths(name="xy_api", project="$(BASE)")
        self.assertIn(
            f"GENERATED := \\\n  $(GEN)/{paths['h']} \\\n  $(GEN)/{paths['lua']} \\\n  $(GEN)/lua/i64.lua\n\n", out
        )
        self.assertIn(" --outputs=h,lua\n", out)

    def test_a_static_link_is_passed_on_to_generation(self) -> None:
        code, out = self.run_gendeps(["--link=static", "--outputs=rs", self.definition()])
        self.assertEqual(code, 0)
        self.assertIn(" --outputs=rs --link=static\n", out)

    def test_a_selection_an_output_refuses_is_left_to_generation(self) -> None:
        code, out = self.run_gendeps(["--link=static", "--outputs=lua", self.definition()])
        self.assertEqual(code, 0)
        self.assertIn(" --outputs=lua --link=static\n", out)

    def test_a_definition_the_loader_refuses_exits_2_with_its_objections_and_nothing_on_stdout(self) -> None:
        definition = self.definition(TWO_BAD_RETURNS)
        code, stdout, stderr = run_main(["gendeps", definition])
        self.assertEqual(code, 2)
        self.assertEqual(stdout, "")
        self.assertEqual(
            stderr.splitlines(),
            [
                f"langxyne: {definition}: function.destroy_port._return: unknown typed_const 'nope'",
                f"langxyne: {definition}: function.spend._return: unknown typed_const 'gone'",
            ],
        )

    def test_unknown_output_is_a_usage_error(self) -> None:
        code, stdout, stderr = run_main(["gendeps", "--outputs=js", "a.adef.toml"])
        self.assertEqual(code, 2)
        self.assertEqual(stdout, "")
        self.assertIn(
            "unknown output 'js' (valid: h, hpp, lua, stub_cpp, rs, abi_rs, stub_rs, go, py, wasm_rs, node)", stderr
        )

    def test_no_definitions_exits_2_with_nothing_on_stdout(self) -> None:
        code, stdout, stderr = run_main(["gendeps"])
        self.assertEqual(code, 2)
        self.assertEqual(stdout, "")
        self.assertEqual(stderr, "langxyne: gendeps takes exactly one definition\n")

    def test_two_definitions_exits_2_with_nothing_on_stdout(self) -> None:
        code, stdout, stderr = run_main(["gendeps", "a.adef.toml", "b.adef.toml"])
        self.assertEqual(code, 2)
        self.assertEqual(stdout, "")
        self.assertEqual(stderr, "langxyne: gendeps takes exactly one definition\n")

    def test_bad_name_exits_2_with_nothing_on_stdout(self) -> None:
        code, out = self.run_gendeps(["not_a_definition.txt"])
        self.assertEqual(code, 2)
        self.assertEqual(out, "")


class GendepsMake(unittest.TestCase):
    DEFINITION = "a.adef.toml"  # unlike KITCHEN_SINK's _name, which names the outputs

    def make_n(self, *flags: str) -> str:
        """`make -n`, in the directory holding KITCHEN_SINK as `DEFINITION`, over the gendeps
        fragment for `flags`, printing each GENERATED target and then the recipe make would
        run; returns make's stdout."""
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            write(root / self.DEFINITION, KITCHEN_SINK)
            with contextlib.chdir(root):
                code, fragment, stderr = run_main(["gendeps", *flags, self.DEFINITION])
            self.assertEqual(code, 0, stderr)
            write(root / "frag.mk", fragment)
            result = run(["make", "-n", "-f", FIXTURES / "gendeps.mk", "all"], cwd=root)
            self.assertEqual(result.returncode, 0, result.stderr)
            return result.stdout

    def test_fragment_drives_gnu_make(self) -> None:
        out = self.make_n()
        self.assertIn("PYTHONPATH=/pkg", out)
        self.assertIn(
            "python3 -m langxyne a.adef.toml --generated OUTDIR --project xy --outputs=h,hpp,lua,stub_cpp,rs,abi_rs,stub_rs,go,py\n",
            out,
        )

    def test_subset_fragment_makes_only_its_outputs(self) -> None:
        out = self.make_n("--outputs=hpp,lua")
        self.assertIn("python3 -m langxyne a.adef.toml --generated OUTDIR --project xy --outputs=hpp,lua\n", out)
        self.assertIn(
            "echo target=OUTDIR/include/xy/xy_api.hpp target=OUTDIR/lua/xy_api.lua target=OUTDIR/lua/i64.lua\n",
            out,
        )


if __name__ == "__main__":
    unittest.main()
