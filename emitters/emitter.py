"""The shape every output's module has, as the generator calls it, the one runner of the
formatters some outputs pass their text through, and the one home of the banner text."""

import subprocess
from pathlib import Path
from typing import Protocol

from langxyne.model import Api

NO_LIBRARY = "no library named; set _general._bound_library or --library"
"""The objection of every output that loads or links the library where `api.library` names none."""

GENERATOR = "langxyne"
"""The generator's name, as every banner spells it."""


def banner(source_name: str) -> str:
    """A regenerated output's banner, without its comment syntax."""
    return f"GENERATED by {GENERATOR} from {source_name}; do not edit."


def stub_banner(source_name: str) -> str:
    """An implementation stub's banner, without its comment syntax: handed over once, never
    regenerated over the implementation."""
    return (
        f"GENERATED by {GENERATOR} from {source_name}: implementation stub. Copy beside the implementation once "
        "and replace every body; the generator never touches it afterwards."
    )


def companion_banner(output: str) -> str:
    """A generated companion's banner, without its comment syntax: it is generated with the
    output `output`, whose own banner names the source."""
    return f"GENERATED by {GENERATOR} beside {output}; do not edit."


def go_banner(source_name: str) -> str:
    """The Go binding's banner, comment syntax included, in the form Go's tools recognise as
    generated (`^// Code generated .* DO NOT EDIT\\.$`)."""
    return f"// Code generated by {GENERATOR} from {source_name}; DO NOT EDIT."


class ToolError(Exception):
    """An external tool an `emit` runs is missing or failed; the message says which and
    why, for the generator to report."""


def formatted(argv: list[str], text: str, *, outputs: str, output: str) -> str:
    """`text` as the formatter `argv` lays it out, read from stdin and written to stdout;
    `ToolError` where `argv[0]` is not on `PATH` (`<tool> is required for <outputs> ...`) or
    exits non-zero (`<tool> failed on <output>: <its stderr>`)."""
    tool = argv[0]
    try:
        result = subprocess.run(argv, input=text, capture_output=True, encoding="utf-8")
    except FileNotFoundError as e:
        raise ToolError(f"{tool} is required for {outputs} and was not found on PATH") from e
    if result.returncode != 0:
        raise ToolError(f"{tool} failed on {output}: {result.stderr.strip()}")
    return result.stdout


class Emitter(Protocol):
    """An output module: its label, its objections, its path, its text and its companions. A
    new emitter starts as a copy of these five signatures; each ignores the keywords it does
    not use.

    `LABEL` heads each of its objections. `validate` returns every objection the output
    has to `api`, each prefixed `<LABEL>: `. `output_path` is where the output lands,
    relative to the generated directory. `emit` renders the output's text from an `api`
    its `validate` accepted, `project` being the project's name, its directory's, and raises
    `ToolError` when a tool it runs is missing or fails. `companions` is every further file
    the output brings for `api`, each (path relative to the generated directory, text),
    written and listed beside the output; most outputs have none. An output that loads or
    links the library reads it from `api.library`, which the generator has resolved."""

    LABEL: str

    def validate(self, api: Api) -> list[str]: ...

    def output_path(self, *, name: str, project: str) -> Path: ...

    def emit(self, api: Api, *, source_name: str, name: str, project: str) -> str: ...

    def companions(self, api: Api, *, name: str) -> list[tuple[Path, str]]: ...
